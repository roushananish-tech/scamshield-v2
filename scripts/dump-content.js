// Writes docs/CONTENT.md: every user-facing string from the data modules, in one
// readable file, so the UI author can review copy without reading code.
// Run: npm run content
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { INCIDENTS, buildPlan, DISCLAIMER } from '../src/engine/lostMoney.js';
import { PANIC, FOUR_RULES, FAMILY_CODEWORD } from '../src/engine/panic.js';
import { QUIZ_CARDS } from '../src/engine/quiz.js';
import { RULES, ADVICE } from '../src/engine/rules.js';
import { parentMessage, quizShare } from '../src/engine/share.js';
import { PLAYBOOKS } from '../src/engine/playbook.js';

const out = ['# ScamShield: all user-facing content', '', '_Generated by `npm run content`. Source of truth is the code in `src/engine/`._', ''];

out.push('## 1. "I lost money" plans', '', `Disclaimer shown under every plan: ${DISCLAIMER}`, '');
for (const id of Object.keys(INCIDENTS)) {
  const p = buildPlan(id);
  out.push(`### ${p.label}  (\`${id}\`)`, '', `_${p.reassure}_`, '');
  for (const s of p.steps) out.push(`${s.n}. **${s.title}**${s.urgent ? ' (urgent)' : ''} [${s.owner}]  `, `   ${s.detail}`);
  out.push('');
}

out.push('## 2. "I am on a call right now" cards', '');
for (const [k, p] of Object.entries(PANIC)) {
  out.push(`### ${p.label}  (\`${k}\`)`, '', `**${p.headline}**`, '', 'Do now:', ...p.doNow.map((x, i) => `${i + 1}. ${x}`), '', 'They will say:', ...p.theyWillSay.map((x) => `- ${x}`), '', 'Afterwards:', ...p.afterwards.map((x) => `- ${x}`), '');
}
out.push('### Four rules', '', ...FOUR_RULES.map((x, i) => `${i + 1}. ${x}`), '', `### ${FAMILY_CODEWORD.title}`, '', ...FAMILY_CODEWORD.steps.map((x, i) => `${i + 1}. ${x}`), '');

out.push('## 3. "Spot the scam" cards', '');
for (const c of QUIZ_CARDS) out.push(`- **${c.truth.toUpperCase()}** (${c.channel}): "${c.text}"`, `  - Lesson: ${c.teach}`);
out.push('');

out.push('## 4. Share messages', '', '### To a parent', '', '```', parentMessage('https://YOUR-URL'), '```', '', '### Quiz score', '', '```', quizShare(4, 6, 'https://YOUR-URL'), '```', '');

out.push('## 5. Detection rules (title and explanation shown to users)', '');
for (const r of RULES) out.push(`- \`${r.id}\` [${r.category}, weight ${r.weight}] **${r.title}**: ${r.why}`);
out.push('', '## 6. Advice lines by category', '', ...Object.entries(ADVICE).map(([k, v]) => `- \`${k}\`: ${v}`), '');

out.push('## 7. Older "what I did" playbooks', '');
for (const [k, p] of Object.entries(PLAYBOOKS)) out.push(`### ${p.title} (\`${k}\`)`, ...p.steps.map((x, i) => `${i + 1}. ${x}`), '');

const target = fileURLToPath(new URL('../docs/CONTENT.md', import.meta.url));
writeFileSync(target, out.join('\n'));
console.log(`wrote ${target}`);
